import { expect, test, type Page } from '@playwright/test'
import { openSynthetic, savesFolder } from './fixtures'

const changes = (page: Page) => page.getByRole('banner').getByRole('button', { name: /change/ })

test('inventory: categories, sorting, and adding from all items', async ({ page }) => {
  await openSynthetic(page, 'inventory')
  const main = page.getByRole('main')
  await expect(main.getByRole('listitem')).toHaveCount(2)
  await main.getByRole('combobox', { name: 'Sort' }).selectOption('most')
  await expect(main.getByRole('listitem').first()).toContainText('Coin')
  await main.getByRole('button', { name: 'All items' }).click()
  await expect.poll(() => main.getByRole('listitem').count()).toBeGreaterThan(100)
  await main.getByRole('button', { name: /^Seeds/ }).click()
  await expect(main.getByRole('listitem').first()).toContainText('Seed')
  await main.getByRole('button', { name: /^All \d/ }).click()
  await main.getByLabel('Search items').fill('berry')
  await main.getByLabel('Berry', { exact: true }).fill('5')
  await main.getByLabel('Berry', { exact: true }).press('Enter')
  await expect(changes(page)).toHaveText('1 change')
})

test('every card has details: description on demand, unlock from the card', async ({ page }) => {
  await openSynthetic(page, 'collection')
  await page.getByRole('tab', { name: 'Tarot' }).click()
  await page.getByRole('button', { name: "Details: Fervour's Host" }).click()
  const dialog = page.getByRole('dialog', { name: "Fervour's Host" })
  await expect(dialog.locator('.desc')).not.toBeEmpty()
  await dialog.getByRole('button', { name: 'Unlock' }).click()
  await expect(dialog).toContainText('Owned')
  await expect(changes(page)).toHaveText('1 change')
  await dialog.getByRole('button', { name: 'Close' }).click()
  await page.getByRole('navigation', { name: 'Sections' }).getByRole('link', { name: 'Inventory' }).click()
  await page.getByRole('button', { name: 'Details: Lumber' }).click()
  await expect(page.getByRole('dialog', { name: 'Lumber' }).getByLabel('Quantity', { exact: true })).toHaveValue('12')
})

test('search finds items it does not own and opens them', async ({ page }) => {
  await openSynthetic(page)
  await page.getByRole('banner').getByRole('button', { name: 'Search' }).click()
  const palette = page.getByRole('dialog', { name: 'Search' })
  await palette.getByRole('combobox').fill('berry')
  await expect(palette.getByRole('option', { name: /^Berry/ }).first()).toBeVisible()
  await palette.getByRole('option', { name: /^Berry/ }).first().click()
  await expect(page).toHaveURL(/#\/inventory\?q=Berry/)
  await expect(page.getByRole('dialog', { name: 'Berry' })).toBeVisible()
})

test('switching slots keeps each slot\'s changes', async ({ page }) => {
  await page.goto('/')
  await page.getByLabel('Choose your saves folder').setInputFiles(await savesFolder(undefined, {}, [0, 1]))
  await page.getByRole('listitem').filter({ hasText: 'slot_0.mp' }).getByRole('button', { name: 'Open' }).click()
  await page.getByRole('main').getByLabel('Gold', { exact: true }).fill('999')
  await page.getByRole('main').getByLabel('Gold', { exact: true }).press('Enter')
  await expect(changes(page)).toHaveText('1 change')
  await page.getByRole('button', { name: 'Switch save' }).click()
  await page.getByRole('menuitemradio').filter({ hasText: 'slot_1.mp' }).click()
  await expect(page.getByRole('banner')).toContainText('slot_1.mp')
  await expect(changes(page)).toHaveText('0 changes')
  await page.getByRole('button', { name: 'Switch save' }).click()
  await expect(page.getByRole('menuitemradio').filter({ hasText: 'slot_0.mp' })).toContainText('1 unexported')
  await page.getByRole('menuitemradio').filter({ hasText: 'slot_0.mp' }).click()
  await expect(changes(page)).toHaveText('1 change')
  await expect(page.getByRole('main').getByLabel('Gold', { exact: true })).toHaveValue('999')
})
