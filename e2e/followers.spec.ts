test('ticks follow the follower through a remove and a revive', async ({ page }) => {
  await openSynthetic(page, 'followers')
  const table = page.getByRole('table'), inspector = page.getByRole('complementary', { name: 'Inspector' })
  await table.getByRole('checkbox', { name: 'Select Ash' }).check()
  await table.getByRole('button', { name: 'Pip' }).click()
  page.once('dialog', d => d.accept())
  await inspector.getByRole('button', { name: 'Remove', exact: true }).click()
  await expect(inspector).toBeHidden()
  await table.getByRole('button', { name: 'Thistle' }).click()
  await inspector.getByRole('button', { name: 'Revive' }).click()
  await expect(inspector).toContainText('ID 3')
  await expect(inspector.getByRole('button', { name: 'Revive' })).toBeHidden()
  await expect(table.getByRole('checkbox', { name: 'Select Ash' })).toBeChecked()
  await expect(table.getByRole('checkbox', { name: 'Select Thistle' })).not.toBeChecked()
  const bar = page.getByRole('region', { name: 'Selected followers' })
  await expect(bar).toContainText('1 selected')
  await bar.getByRole('button', { name: 'Max needs' }).click()
  await changes(page).click()
  const review = page.getByRole('dialog', { name: 'Review changes' })
  await expect(review).toContainText('Ash · needs maxed')
  await expect(review).not.toContainText('Thistle · needs')
})

test('undo and redo keep the inspector on the same follower; undoing a selected clone closes it', async ({ page }) => {
  await openSynthetic(page, 'followers')
  const table = page.getByRole('table'), inspector = page.getByRole('complementary', { name: 'Inspector' })
  await table.getByRole('button', { name: 'Pip' }).click()
  page.once('dialog', d => d.accept())
  await inspector.getByRole('button', { name: 'Remove', exact: true }).click()
  await table.getByRole('button', { name: 'Ash' }).click()
  await expect(inspector).toContainText('ID 2')
  await page.keyboard.press('ControlOrMeta+z')
  await expect(table.getByRole('row').nth(1)).toContainText('Pip')
  await expect(inspector).toContainText('ID 2')
  await page.keyboard.press('ControlOrMeta+Shift+z')
  await expect(inspector).toContainText('ID 2')
  await inspector.getByRole('button', { name: 'Clone' }).click()
  await table.getByRole('button', { name: 'Ash' }).nth(1).click()
  await expect(inspector).toContainText('ID 4')
  await page.keyboard.press('ControlOrMeta+z')
  await expect(inspector).toBeHidden()
})

test('switching slots or leaving the page clears the ticks; switching closes the inspector', async ({ page }) => {
  await page.goto('/')
  await page.getByLabel('Choose your saves folder').setInputFiles(await savesFolder(undefined, {}, [0, 1]))
  await page.getByRole('listitem').filter({ hasText: 'slot_0.mp' }).getByRole('button', { name: 'Open' }).click()
  await page.getByRole('navigation', { name: 'Sections' }).getByRole('link', { name: /followers/i }).click()
  const table = page.getByRole('table'), bar = page.getByRole('region', { name: 'Selected followers' })
  await table.getByRole('checkbox', { name: 'Select Pip' }).check()
  await table.getByRole('checkbox', { name: 'Select Ash' }).check()
  await table.getByRole('button', { name: 'Ash' }).click()
  await expect(bar).toBeVisible()
  for (const file of ['slot_1.mp', 'slot_0.mp']) {
    await page.getByRole('button', { name: 'Switch save' }).click()
    await page.getByRole('menuitemradio').filter({ hasText: file }).click()
    await expect(page.getByRole('button', { name: 'Switch save' })).toContainText(file)
    await expect(bar).toBeHidden()
    await expect(page.getByRole('complementary', { name: 'Inspector' })).toBeHidden()
    await expect(table.getByRole('checkbox', { name: 'Select Pip' })).not.toBeChecked()
    await expect(changes(page)).toHaveText('0 changes')
  }
  await table.getByRole('checkbox', { name: 'Select Pip' }).check()
  const nav = page.getByRole('navigation', { name: 'Sections' })
  await nav.getByRole('link', { name: /overview/i }).click()
  await nav.getByRole('link', { name: /followers/i }).click()
  await expect(table.getByRole('checkbox', { name: 'Select Pip' })).not.toBeChecked()
  await expect(bar).toBeHidden()
})
